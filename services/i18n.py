def translate(text: str, language: str = "en") -> str:
    """Translate a UI string to the target language.
    Returns the original text if no translation is available."""
    if language == "fa":
        return TRANSLATIONS.get(text, text)
    return text


def is_rtl(language: str) -> bool:
    """True if the language is right-to-left."""
    return language == "fa"


def to_persian_digits(text: str) -> str:
    """Convert Western digits 0-9 inside *text* to Persian-Indic digits.

    Only digits are converted — punctuation, letters and symbols are kept.
    Use this for ordinal UI counts ("3 servers"), NOT for technical values
    like ports (":22"), IPs (10.0.0.1), versions ("v1.2.3") or percentages
    ("75%") which the Iranian tech community still writes in Western form.
    """
    if not text:
        return text
    return text.translate(_PERSIAN_DIGITS)


def looks_technical(text: str) -> bool:
    """True if the text contains technical markers (URL, IP, port-colon, version).

    Used to decide whether to_persian_digits() should be skipped. Technical
    values like '0.0.0.0:22', 'https://...', 'v1.2.3', '75%' must stay Western
    per Behdad Esfahbod's note (Persian Computing Unicode): "in Iran people
    read and write western digits in a Latin context".
    """
    if not text:
        return False
    # Bare digits-only string with no surrounding chars is technical (port/size).
    if text.strip().isdigit():
        return True
    return bool(_TECH_RE.search(text))


def smart_digits(text: str, language: str = "en") -> str:
    """Translate then convert digits to Persian-Indic — but only if the
    string doesn't look technical (ports, IPs, versions, percentages).

    Use this for things like toast messages, nav-badge counts and short
    labels such as "3 servers". The translation step runs first so any
    half-spaces from the Persian dictionary are preserved.
    """
    out = translate(text, language)
    if language == "fa" and not looks_technical(text):
        return to_persian_digits(out)
    return out


# Icon-mirroring table for RTL.
# Per Material 3 bidirectionality rules:
#  - Directional icons (back/forward, send, play) MUST be mirrored in RTL.
#  - Non-directional icons (clock, refresh, search, settings) MUST NOT be mirrored.
#  - Icons that depict real-world objects with an inherent direction (a printer,
#    a phone, a trash can) are NOT mirrored.
# Flet doesn't expose a per-icon "flip" flag, so callers swap the icon name
# itself using this table.
RTL_ICON_MIRROR = {
    # Flet icon names — values are the mirrored equivalents.
    # Back/forward arrows.
    "arrow_back": "arrow_forward",
    "arrow_back_ios": "arrow_forward_ios",
    "arrow_back_ios_new": "arrow_forward_ios",
    "arrow_forward": "arrow_back",
    "arrow_forward_ios": "arrow_back_ios",
    # Chevron / play / skip
    "chevron_left": "chevron_right",
    "chevron_right": "chevron_left",
    "keyboard_arrow_left": "keyboard_arrow_right",
    "keyboard_arrow_right": "keyboard_arrow_left",
    "play_arrow": "play_arrow",        # play stays a triangle, but culturally
                                        # points the other way; Flet uses the
                                        # same glyph name, so we leave it alone
                                        # and let the platform theme mirror it.
    "first_page": "last_page",
    "last_page": "first_page",
    # Reply / forward / share (directional)
    "reply": "reply",                   # Flet's reply glyph is symmetric
    "send": "send",                     # send is directional — keep name,
                                        # rely on platform mirroring
    "share": "share",
    # List / formatting indentation (directional in text editors)
    "format_indent_increase": "format_indent_increase",
    "format_indent_decrease": "format_indent_decrease",

}


def mirror_icon(name: str, language: str = "en") -> str:
    """Return the RTL-mirrored icon name for the given language.

    For LTR languages this is a no-op. For RTL, directional icons are swapped
    using :data:`RTL_ICON_MIRROR`. Icons not in the table stay as-is (which is
    correct for non-directional icons like clocks, refresh, settings, etc.).
    """
    if language != "fa":
        return name
    return RTL_ICON_MIRROR.get(name, name)


# Persian font family — Vazirmatn is the de-facto standard for Persian UIs
# (https://github.com/rastikerdar/vazirmatn). Flet's bundled Material fonts
# don't shape Persian correctly; setting font_family="Vazirmatn" lets the
# Flutter text renderer pick a Persian-aware font when the platform has
# Vazirmatn installed, and falls back to the default sans-serif otherwise.
PERSIAN_FONT_FAMILY = "Vazirmatn"


def font_for(language: str = "en") -> str | None:
    """Return the recommended font family for the given language, or None
    to use the platform default."""
    if language == "fa":
        return PERSIAN_FONT_FAMILY
    return None

